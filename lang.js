// ===========================
// LANGUAGE STATE
// ===========================
let currentLang = localStorage.getItem('financeai_lang') || 'en';

// ===========================
// APPLY LANGUAGE
// ===========================
function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('financeai_lang', lang);

  const t = TRANSLATIONS[lang];

  // Update all data-en / data-es elements
  document.querySelectorAll('[data-en]').forEach(el => {
    const text = lang === 'en'
      ? el.getAttribute('data-en')
      : el.getAttribute('data-es');
    if (text) el.innerHTML = text;
  });

  // Update all data-key elements
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-placeholder-en]').forEach(el => {
    const placeholder = lang === 'en'
      ? el.getAttribute('data-placeholder-en')
      : el.getAttribute('data-placeholder-es');
    if (placeholder) el.placeholder = placeholder;
  });

  // Update lang button
  const langBtn = document.querySelector('.btn-lang');
  if (langBtn) {
    langBtn.textContent = lang === 'en' ? '🌐 ES' : '🌐 EN';
  }

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Dispatch event for other scripts
  window.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));
}

// ===========================
// TOGGLE LANGUAGE
// ===========================
function toggleLang() {
  const newLang = currentLang === 'en' ? 'es' : 'en';
  
  applyLanguage(newLang);
}

// ===========================
// GET TRANSLATION
// ===========================
function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['en'][key] || key;
}

// ===========================
// INIT ON LOAD
// ===========================
document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
});

// ===========================
// EXPORT
// ===========================
window.FinanceAILang = {
  toggle: toggleLang,
  apply: applyLanguage,
  get: t,
  current: () => currentLang,
  translations: TRANSLATIONS
};

// ===========================
// SET LANG (alias for buttons)
// ===========================
function setLang(lang) {
  applyLanguage(lang);

  // Update active state on all lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active');
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('onclick') && btn.getAttribute('onclick').includes(`'${lang}'`)) {
      btn.classList.add('active');
    }
  });
}
window.setLang = setLang;

